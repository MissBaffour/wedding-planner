import { uuidv7 } from '@kasadesk/shared';
import { sql } from 'kysely';
import { z } from 'zod';
import { withTenant, type DB, type Tx } from '../../platform/db/index.ts';
import { AppError, Errors } from '../../platform/errors.ts';
import type { TenantState } from '../../platform/http/types.ts';
import { emit } from '../../platform/outbox.ts';
import { preview } from '../conversations/ingest.ts';
import { buildTemplateSend, type TemplateComponent } from '../channels/whatsapp/templates.ts';
import { isWithinServiceWindow, windowClosesAt } from '../channels/whatsapp/window.ts';

export const SendMessageBody = z.object({
  /** Generated by the PWA before sending; re-sending the same id never duplicates (offline retries). */
  clientId: z.string().uuid(),
  text: z.string().trim().min(1).max(4096).optional(),
  template: z.object({
    name: z.string().min(1).max(512),
    language: z.string().min(2).max(15),
    headerParams: z.array(z.string().max(1024)).max(10).optional(),
    bodyParams: z.array(z.string().max(1024)).max(30).optional(),
  }).optional(),
  replyToMessageId: z.string().uuid().optional(),
}).refine((b) => Boolean(b.text) !== Boolean(b.template), { message: 'Send either text or template' });

export type SendMessageInput = z.infer<typeof SendMessageBody>;

/** Latest inbound message time for this customer on this channel (the WhatsApp 24h window). */
export async function lastInboundAt(tx: Tx, contactId: string, channelId: string): Promise<Date | null> {
  const r = await sql<{ at: Date | null }>`
    select max(created_at) as at from messages
     where contact_id = ${contactId} and channel_id = ${channelId} and direction = 'inbound'`.execute(tx);
  return r.rows[0]?.at ?? null;
}

export async function queueAgentMessage(db: DB, t: TenantState, conversationId: string, input: SendMessageInput) {
  return withTenant(db, t, async (tx) => {
    const replay = await tx.selectFrom('messages').selectAll().where('client_id', '=', input.clientId).executeTakeFirst();
    if (replay) {
      if (replay.conversation_id !== conversationId) throw Errors.conflict('client_id_reused');
      return { message: replay, created: false };
    }

    const conv = await tx.selectFrom('conversations')
      .innerJoin('channels', 'channels.id', 'conversations.channel_id')
      .innerJoin('contacts', 'contacts.id', 'conversations.contact_id')
      .select([
        'conversations.id', 'conversations.status', 'conversations.contact_id', 'conversations.channel_id',
        'channels.type as channel_type', 'channels.status as channel_status', 'contacts.blocked',
      ])
      .where('conversations.id', '=', conversationId)
      .executeTakeFirst();
    if (!conv) throw Errors.notFound('conversation_not_found');
    if (conv.channel_status !== 'active') throw Errors.conflict('channel_inactive', 'This channel is disconnected. Reconnect it in Settings.');
    if (conv.blocked) throw Errors.conflict('contact_blocked', 'This customer is blocked.');

    let kind: 'text' | 'template' = 'text';
    let body = input.text ?? '';
    let payload: Record<string, unknown> = {};

    if (input.template) {
      if (conv.channel_type !== 'whatsapp') throw Errors.badRequest('templates_whatsapp_only', 'Templates are only for WhatsApp.');
      const tpl = await tx.selectFrom('whatsapp_templates').select(['name', 'language', 'status', 'components'])
        .where('channel_id', '=', conv.channel_id).where('name', '=', input.template.name)
        .where('language', '=', input.template.language).executeTakeFirst();
      if (!tpl) throw Errors.badRequest('template_not_found', 'Template not found. Sync templates and try again.');
      if (tpl.status.toUpperCase() !== 'APPROVED') throw Errors.badRequest('template_not_approved', `Template status is ${tpl.status}.`);
      let built;
      try {
        built = buildTemplateSend(tpl.components as TemplateComponent[], input.template);
      } catch (err) {
        throw Errors.badRequest('template_params_invalid', (err as Error).message);
      }
      kind = 'template';
      body = built.preview;
      payload = { template: { name: tpl.name, language: tpl.language, components: built.components } };
    } else if (conv.channel_type === 'whatsapp') {
      const last = await lastInboundAt(tx, conv.contact_id, conv.channel_id);
      if (!isWithinServiceWindow(last)) {
        throw new AppError(422, 'outside_service_window',
          'More than 24 hours since the customer last wrote. Send an approved template instead.',
          { lastInboundAt: last, windowClosedAt: windowClosesAt(last) });
      }
    }

    let replyToId: string | null = null;
    if (input.replyToMessageId) {
      const r = await tx.selectFrom('messages').select('id').where('id', '=', input.replyToMessageId)
        .where('conversation_id', '=', conversationId).executeTakeFirst();
      if (!r) throw Errors.badRequest('reply_target_not_found');
      replyToId = r.id;
    }

    // Sending into a resolved conversation reopens it, unless a newer one is already open.
    if (conv.status === 'resolved') {
      const open = await tx.selectFrom('conversations').select('id').where('contact_id', '=', conv.contact_id)
        .where('channel_id', '=', conv.channel_id).where('status', '<>', 'resolved').executeTakeFirst();
      if (open) throw Errors.conflict('newer_conversation_open', 'Reply in the open conversation.', { conversationId: open.id });
      await tx.updateTable('conversations').set((eb) => ({ status: 'pending', resolved_at: null, reopened_count: eb('reopened_count', '+', 1) }))
        .where('id', '=', conversationId).execute();
      await tx.insertInto('conversation_events').values({
        id: uuidv7(), business_id: t.businessId, conversation_id: conversationId, type: 'reopened', actor_type: 'agent', actor_id: t.membershipId, data: '{}',
      }).execute();
    }

    const id = uuidv7();
    const message = await tx.insertInto('messages')
      .values({
        id, business_id: t.businessId, conversation_id: conversationId, contact_id: conv.contact_id, channel_id: conv.channel_id,
        direction: 'outbound', sender_type: 'agent', sender_id: t.membershipId, kind, body, payload: JSON.stringify(payload),
        client_id: input.clientId, reply_to_id: replyToId, status: 'queued',
      })
      .returningAll()
      .executeTakeFirstOrThrow();

    await tx.updateTable('conversations')
      .set({ last_message_at: new Date(), last_message_preview: preview(body, kind), unread_count: 0 })
      .where('id', '=', conversationId).execute();
    await emit(tx, t.businessId, 'message.send', { messageId: id });
    await emit(tx, t.businessId, 'message.created', { conversationId, messageId: id, direction: 'outbound' });
    return { message, created: true };
  });
}
